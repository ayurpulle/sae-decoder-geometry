"""Phase 3, interpolation: does gamma(k) move from the sparse planted regime toward the Gaussian one as density rises?

Point features, isotropic directions (beta = 0), d = 256, p_i ∝ i^-1.5, noise 0.05, with features per dimension and
active features per token raised together (M/d = 2 -> 16, active 4 -> 32):
    s2-point (512, 4)  [stage 2]   i-m1024-a8   i-m2048-a16   i-m4096-a32
The last has stage 1's density but random directions, separating density from stage 1's direction crowding (beta = 1).
Per dataset: TopK width 4096, k in K_SWEEP, real vs Gaussian twin, 2 epochs over 5.5M tokens, seed 0.
Prediction of the blend hypothesis: as density rises, real gamma(k)'s intercept and k-slope move from the sparse
values (0.22, -0.04 per doubling) toward the Gaussian twin's (1.35, -0.22), passing Gemma's (1.02, -0.094) on the way.
Usage: python experiments/phase3_interp.py
"""
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ["--d", 256, "--alpha", 0.5, "--beta", 0, "--noise", 0.05]
DATASETS = {"s2-point": ("saes_p3s2", None),  # already generated by phase3_stage2.py
            "i-m1024-a8": ("saes_p3i", ["--M", 1024, "--mean_active", 8]),
            "i-m2048-a16": ("saes_p3i", ["--M", 2048, "--mean_active", 16]),
            "i-m4096-a32": ("saes_p3i", ["--M", 4096, "--mean_active", 32])}
K_SWEEP = [4, 8, 16, 32, 64]
WIDTH, TOKENS, EVAL, EPOCHS = 4096, 6_000_000, 500_000, 2


def py(*args):
    subprocess.run([sys.executable, "-u", *map(str, args)], check=True, cwd=ROOT)


def main():
    for data, (_, flags) in DATASETS.items():
        if flags and not (ROOT / "cache" / "acts" / f"synth-{data}" / "blocks.0.hook_resid_post" / "acts.npy").exists():
            py(ROOT / "synth.py", "--name", data, "--n_tokens", TOKENS, *BASE, *flags)
    for k in K_SWEEP:
        for data, (group, _) in DATASETS.items():
            for cond in ["real", "gaussian"]:
                name = f"synth-{data}__blocks.0.hook_resid_post__{cond}__w{WIDTH}__k{k}__s0"
                if (ROOT / "cache" / group / name / "train.json").exists():
                    continue
                py(ROOT / "train_sae.py", "--model", f"synth-{data}", "--hook", "blocks.0.hook_resid_post",
                   "--cond", cond, "--width", WIDTH, "--k", k, "--tokens", TOKENS, "--eval_tokens", EVAL,
                   "--epochs", EPOCHS, "--seed", 0, "--out", f"cache/{group}")
    for group in sorted({g for g, _ in DATASETS.values()}):
        py(ROOT / "experiments" / "phase3_analyze.py", group, "--match")


if __name__ == "__main__":
    main()
