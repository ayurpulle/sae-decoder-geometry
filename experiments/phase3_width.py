"""Phase 3, width sweep: does SAE width set the k-scale k0 of gamma(k)?

The interpolation (phase3_interp.py) found every planted fit on one ray, gamma(k) ≈ A·(1 − log2 k / log2 k0) with
k0 ≈ 100 at d = 256, width 4096, whatever the density; Gemma's TopK fit (16k wide) has k0 ≈ 1800. Here the density
nearest Gemma's intercept (i-m2048-a16: M = 2048, 16 active, beta = 0) is held fixed and the width varied:
    width in {1024, 2048, 4096 [from saes_p3i], 8192, 16384}, k in K_SWEEP, real vs Gaussian twin, seed 0.
If width sets k0, log2 k0 should rise with log2 width; if not, the k-scale comes from d or the recipe.
Runs go smallest width first so partial results are usable. Usage: python experiments/phase3_width.py
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = "i-m2048-a16"  # generated by phase3_interp.py
WIDTHS = [1024, 2048, 8192, 16384]
K_SWEEP = [4, 8, 16, 32, 64]
TOKENS, EVAL, EPOCHS = 6_000_000, 500_000, 2
GROUP = "saes_p3w"


def py(*args):
    subprocess.run([sys.executable, "-u", *map(str, args)], check=True, cwd=ROOT)


def main():
    for w in WIDTHS:
        for k in K_SWEEP:
            for cond in ["real", "gaussian"]:
                name = f"synth-{DATA}__blocks.0.hook_resid_post__{cond}__w{w}__k{k}__s0"
                if (ROOT / "cache" / GROUP / name / "train.json").exists():
                    continue
                py(ROOT / "train_sae.py", "--model", f"synth-{DATA}", "--hook", "blocks.0.hook_resid_post",
                   "--cond", cond, "--width", w, "--k", k, "--tokens", TOKENS, "--eval_tokens", EVAL,
                   "--epochs", EPOCHS, "--seed", 0, "--out", f"cache/{GROUP}")
        py(ROOT / "experiments" / "phase3_analyze.py", GROUP)  # refresh after each width


if __name__ == "__main__":
    main()
