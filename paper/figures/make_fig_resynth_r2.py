"""Figure: resynthesis control G vs D with 6 replicates (3 data draws x 2 SAE seeds), all four rank windows.

Reads only results/r2/resynth_analysis.json (written by experiments/r2_resynth_analysis.py from runs_resynth.jsonl).
Writes paper/figures/fig7_resynth_r2.{pdf,png} and prints the numbers the caption quotes.
Run from anywhere:  python paper/figures/make_fig_resynth_r2.py
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_figures import OI, RES, W2, WINDOWS, WIN_LABEL, log2_axis, panel_tag, plt, save  # noqa: E402

A = json.load(open(RES / "r2" / "resynth_analysis.json"))
KS = A["k"]
COL = {"D": OI["blue"], "G": OI["purple"]}
MK = {"D": "D", "G": "o"}
LAB = {"D": "D: Gemma Scope rows, permuted", "G": "G: Gaussian directions, matched covariance"}


def main():
    fig, axes = plt.subplots(2, 2, figsize=(W2 * 0.8, 3.7), sharex=True)
    axes = axes.ravel()
    nums = {}
    for ax, w, tag in zip(axes, WINDOWS, "abcd"):
        for X in "DG":
            c = A["curves"][X][w]["gamma_fixed"]
            for ys in c["per_replicate"].values():
                ax.plot(KS, ys, "-", color=COL[X], lw=0.4, alpha=0.35)
            ax.errorbar(KS, c["mean"], yerr=c["sd"], color=COL[X], marker=MK[X], ms=2.8, capsize=1.2,
                        elinewidth=0.6, lw=1.0, label=LAB[X])
        r1 = A["k8_128"]["windows"][w]["fixed"]
        r2 = A["k16_128_posthoc"]["windows"][w]["fixed"]
        ax.set_title(f"{WIN_LABEL[w]}; G/D {r1['gamma']['retained']:.2f} (k 8–128), "
                     f"{r2['gamma']['retained']:.2f} (k 16–128)", fontsize=6.6)
        log2_axis(ax, [8, 16, 32, 64, 128])
        ax.set_xlim(6.5, 160)
        if tag in "cd":
            ax.set_xlabel("k (active latents per token)")
        if tag in "ac":
            ax.set_ylabel(r"$\gamma$, fixed 8,192 live latents")
        panel_tag(ax, tag, x=-0.1)
        nums[w] = {"ret_8_128": r1["gamma"]["retained"], "ret_16_128": r2["gamma"]["retained"]}
    h, l_ = axes[0].get_legend_handles_labels()
    fig.legend(h, l_, loc="lower center", bbox_to_anchor=(0.5, -0.08), ncol=2, fontsize=6.5,
               title="mean ± sd over 6 replicates (3 data draws × 2 SAE seeds); thin lines: replicates",
               title_fontsize=6.3)
    fig.tight_layout(w_pad=1.0, h_pad=0.8)
    save(fig, "fig7_resynth_r2")
    print(json.dumps(nums, indent=1))
    table()


def table():
    """tab_resynth_r2.tex: per-doubling slopes (mean +- sd over 6 replicates) and G/D retention, both k ranges."""
    def ci(m):
        lo, hi = m["retained_boot95"]
        return f"{m['retained']:.2f} [{lo:.3f}, {hi:.3f}]"

    lines = []
    for name, lab in (("k8_128", r"$k=8$--128 (pre-registered)"), ("k16_128_posthoc", r"$k=16$--128 (post hoc)")):
        lines.append(rf"\multicolumn{{8}}{{l}}{{\emph{{{lab}}}}} \\")
        for w in WINDOWS:
            fx, fu = A[name]["windows"][w]["fixed"], A[name]["windows"][w]["full"]
            g = fx["gamma"]
            lines.append(" & ".join([
                WIN_LABEL[w].replace("ranks ", "").replace("–", "--"),
                f"${g['s_D']['mean']:.3f} \\pm {g['s_D']['sd']:.3f}$",
                f"${g['s_G']['mean']:.3f} \\pm {g['s_G']['sd']:.3f}$",
                ci(g), ci(fx["raw"]),
                f"{fu['gamma']['retained']:.2f}", f"{fu['raw']['retained']:.2f}", fx["verdict"]]) + r" \\")
    body = "\n".join(lines)
    tex = (r"""\begin{tabular}{l rr ll rr l}
\toprule
 & \multicolumn{4}{c}{fixed 8,192 live latents} & \multicolumn{2}{c}{full live count} & \\
\cmidrule(lr){2-5}\cmidrule(lr){6-7}
ranks & $s_D$ ($\gamma$) & $s_G$ ($\gamma$) & G/D $\gamma$ [95\%] & G/D raw [95\%] & G/D $\gamma$ & G/D raw & verdict \\
\midrule
""" + body + "\n\\bottomrule\n\\end{tabular}\n")
    p = Path(__file__).resolve().parent / "tab_resynth_r2.tex"
    p.write_text("% generated by paper/figures/make_fig_resynth_r2.py from results/r2/resynth_analysis.json\n" + tex)
    print(tex)


if __name__ == "__main__":
    main()
